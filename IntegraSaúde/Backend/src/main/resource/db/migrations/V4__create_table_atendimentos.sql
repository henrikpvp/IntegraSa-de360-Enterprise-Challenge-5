CREATE TABLE tb_atendimentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id BIGINT NOT NULL,
    medico_id BIGINT,
    queixa_principal TEXT NOT NULL,
    frequencia_cardiaca INT,
    pressao_sistolica INT,
    pressao_diastolica INT,
    temperatura DOUBLE PRECISION,
    saturacao_oxigenio INT,
    escala_dor INT,
    nivel_risco VARCHAR(20),
    status VARCHAR(30) NOT NULL,
    data_hora_chegada TIMESTAMP NOT NULL,
    data_hora_triagem TIMESTAMP,
    data_hora_atendimento TIMESTAMP,
    data_hora_finalizacao TIMESTAMP,
    pontuacao_prioridade DOUBLE PRECISION,
    CONSTRAINT fk_atendimentos_pacientes FOREIGN KEY (paciente_id) REFERENCES tb_pacientes(id),
    CONSTRAINT fk_atendimentos_medicos FOREIGN KEY (medico_id) REFERENCES tb_medicos(id)
);